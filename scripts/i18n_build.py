#!/usr/bin/env python3
"""Build js/i18n/<lang>.js (nl, de, fr, es) from scripts/i18n_strings.txt (English key | nl | de | fr | es).
English is the key itself, so English needs no file; an empty cell (or a missing row) falls back to English in js/i18n.js.
  python3 scripts/i18n_build.py      # then python3 scripts/stamp_assets.py"""
import json, re
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
LANGS = ['nl', 'de', 'fr', 'es']
d = {l: {} for l in LANGS}
for i, line in enumerate((ROOT / 'scripts' / 'i18n_strings.txt').read_text(encoding='utf-8').splitlines(), 1):
    if not line.strip() or line.startswith('#'): continue
    cells = [c.strip() for c in line.split(' | ')]
    if len(cells) != 5: raise SystemExit(f'line {i}: expected 5 cells, got {len(cells)}: {line[:80]}')
    en = cells[0]
    for l, v in zip(LANGS, cells[1:]):
        if not v: continue
        if v == '∅': v = ''
        if l == 'fr': v = re.sub(r' ([?!:;»])', '\u00a0\\1', v).replace('« ', '«\u00a0')   # French spacing, never broken at the line end
        if v and set(re.findall(r'\{\w+\}', en)) != set(re.findall(r'\{\w+\}', v)): raise SystemExit(f'line {i} ({l}): placeholders differ')
        d[l][en] = v
for l in LANGS:
    out = ROOT / 'js' / 'i18n' / f'{l}.js'
    out.parent.mkdir(exist_ok=True)
    out.write_text('/* generated by scripts/i18n_build.py from scripts/i18n_strings.txt — edit that file, not this one */\n'
                   f'(window.TG_I18N = window.TG_I18N || {{ dicts: {{}} }}).dicts.{l} = ' + json.dumps(d[l], ensure_ascii=False, indent=0) + ';\n', encoding='utf-8')
    print(l, len(d[l]), 'strings')
